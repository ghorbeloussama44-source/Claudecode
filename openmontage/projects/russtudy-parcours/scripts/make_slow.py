#!/usr/bin/env python3
"""Build the 60 s "slower pace" versions from the 40 s compositions.

The film is not re-timed by hand: the 40 s timeline is played 1.5x slower. For each 40 s
HyperFrames project (vertical `hyperframes/`, YouTube `hyperframes-16x9/`) this script
writes a 60 s project (`hyperframes-60s/`, `hyperframes-60s-16x9/`) where
  - every data-start / data-duration (scenes, root, soundtrack) is multiplied by 1.5;
  - the timeline handed to the renderer is a 60 s root timeline that scrubs the original
    40 s one (time = t / 1.5): every animation, transition and canvas scene keeps its
    shape and simply plays slower, so retouches made in the 40 s version carry over;
  - the soundtrack is the 60 s mix from `python3 scripts/build_audio.py --slow` (same
    music re-edited so the drops and the final chord still land on the slowed cuts).

    python3 scripts/make_landscape.py && python3 scripts/make_slow.py
"""
import json
import pathlib
import re
import shutil
import sys

K = 1.5
ROOT = pathlib.Path(__file__).resolve().parent.parent
PAIRS = [("hyperframes", "hyperframes-60s"), ("hyperframes-16x9", "hyperframes-60s-16x9")]
SOUND = ROOT / "assets/audio-60s/soundtrack.wav"


def fmt(v: float) -> str:
    return f"{v:.4f}".rstrip("0").rstrip(".")


if not SOUND.exists():
    sys.exit("make_slow: run `python3 scripts/build_audio.py --slow` first (assets/audio-60s/soundtrack.wav)")

for src_name, dst_name in PAIRS:
    src, dst = ROOT / src_name, ROOT / dst_name
    s = (src / "index.html").read_text(encoding="utf-8")
    m = re.search(r'id="root"[^>]*?data-duration="([\d.]+)"', s, re.S)
    if not m:
        sys.exit(f"make_slow: root data-duration not found in {src_name}/index.html")
    dur = float(m.group(1))
    s, n = re.subn(r'data-(start|duration)="([\d.]+)"', lambda g: f'data-{g.group(1)}="{fmt(float(g.group(2)) * K)}"', s)
    old = '      window.__timelines["main"] = tl;\n'
    if s.count(old) != 1 or s.count("Le parcours 40s") != 1:
        sys.exit(f"make_slow: unexpected structure in {src_name}/index.html (timeline registration or <title>)")
    s = s.replace("Le parcours 40s", "Le parcours 60s")
    s = s.replace(old, f"""      // 60 s version (generated by scripts/make_slow.py): the {fmt(dur)} s timeline above is played
      // {fmt(K)}x slower by a root timeline that scrubs it, so every animation keeps its shape.
      const SLOW = {fmt(K)};
      const slowTl = gsap.timeline({{ paused: true }});
      slowTl.fromTo(tl, {{ time: 0 }}, {{ time: {fmt(dur)}, duration: {fmt(dur)} * SLOW, ease: "none", immediateRender: false }}, 0);
      window.__timelines["main"] = slowTl;
""")
    dst.mkdir(exist_ok=True)
    (dst / "index.html").write_text(s, encoding="utf-8")
    for sub_dir in ("fonts", "vendor", "img"):
        shutil.copytree(src / "assets" / sub_dir, dst / "assets" / sub_dir, dirs_exist_ok=True)
    (dst / "assets" / "audio").mkdir(parents=True, exist_ok=True)
    shutil.copy2(SOUND, dst / "assets" / "audio" / "soundtrack.wav")
    for f in ("hyperframes.json", "package.json", "CLAUDE.md", "AGENTS.md"):
        shutil.copy2(src / f, dst / f)
    meta = json.loads((src / "meta.json").read_text())
    meta.update(id=dst_name, name=dst_name)
    (dst / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"{dst_name}/index.html written: {n} timings x {fmt(K)}, {fmt(dur)} s -> {fmt(dur * K)} s")
